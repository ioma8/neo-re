#define FB_BLACK(fb, x, y) ((fb)[((y) >> 3) * RAY_VIEW_W + (x)] |= (uint8_t)(1u << ((y) & 7)))
#define FB_WHITE(fb, x, y) ((fb)[((y) >> 3) * RAY_VIEW_W + (x)] &= (uint8_t)~(1u << ((y) & 7)))
#define FB_INVERT(fb, x, y) ((fb)[((y) >> 3) * RAY_VIEW_W + (x)] ^= (uint8_t)(1u << ((y) & 7)))


static inline uint16_t DivU16(uint16_t numerator, uint16_t denominator) {
    uint32_t value = numerator;
    __asm__ ("divu.w %1,%0" : "+d"(value) : "d"(denominator));
    return (uint16_t)value;
}

static inline int16_t MulQ8(int16_t a, int16_t b) {
    int32_t product = (int32_t)a;
    __asm__ ("muls.w %1,%0" : "+d"(product) : "d"(b));
    return (int16_t)(product >> 8);
}

static inline uint16_t MulU16(uint16_t a, uint16_t b) {
    uint32_t product = a;
    __asm__ ("mulu.w %1,%0" : "+d"(product) : "d"(b));
    return (uint16_t)product;
}


static void PrepareRays(const RayGame_t* game, int16_t* ray_x, int16_t* ray_y) {
    int16_t dir_x = ray_game_dir_x(game);
    int16_t dir_y = ray_game_dir_y(game);
    int16_t plane_x = (int16_t)((-dir_y * CAM_PLANE) >> 7);
    int16_t plane_y = (int16_t)((dir_x * CAM_PLANE) >> 7);
    for(int16_t x = 0; x < RAY_COLS; x++) {
        int16_t cam = CAM256[x];
        ray_x[x] = (int16_t)(dir_x + MulQ8(plane_x, cam));
        ray_y[x] = (int16_t)(dir_y + MulQ8(plane_y, cam));
    }
}

static void DrawFloor(uint8_t* fb) {
    for(uint16_t i = 0; i < FB_BYTES; i++) fb[i] = 0;
    for(int16_t y = RAY_HORIZON + 4; y < RAY_VIEW_H; y += 4) {
        for(int16_t x = 0; x < RAY_VIEW_W; x += 4) {
            FB_BLACK(fb, x, y);
        }
    }
}

static void DrawWallSpan(uint8_t* fb, int16_t x, int16_t top, int16_t bot, bool shaded) {
    uint8_t first;
    uint8_t last;
    uint8_t page;
    if(top < 0) top = 0;
    if(bot >= RAY_VIEW_H) bot = RAY_VIEW_H - 1;
    if(top > bot) return;
    first = (uint8_t)(top >> 3);
    last = (uint8_t)(bot >> 3);
    for(page = first; page <= last; page++) {
        uint8_t mask = 0xffu;
        uint8_t* cell;
        if(page == first) mask &= (uint8_t)(0xffu << (top & 7));
        if(page == last) mask &= (uint8_t)(0xffu >> (7 - (bot & 7)));
        cell = &fb[page * RAY_VIEW_W + x];
        *cell |= mask;
        if(shaded) {
            uint8_t dither = (x & 1) ? 0xaau : 0x55u;
            *cell &= (uint8_t)~(mask & dither);
        }
    }
}

static void DrawWalls(
    const RayGame_t* game,
    uint8_t* fb,
    uint16_t* depth,
    const int16_t* ray_x,
    const int16_t* ray_y
) {
    for(int16_t x = 0; x < RAY_COLS; x++) {
        RayHit_t hit = ray_game_cast_vector(game, ray_x[x], ray_y[x]);
        int16_t top;
        int16_t bot;
        int16_t height;
        if(!hit.hit) {
            depth[x] = 0xffffu;
            continue;
        }
        depth[x] = hit.distance;
        {
            uint16_t projected = DivU16((uint16_t)(RAY_FOCAL * RAY_WALL_HEIGHT), hit.distance < 1 ? 1 : hit.distance);
            height = projected > 2000u ? 2000 : (int16_t)projected;
        }
        top = (int16_t)(RAY_HORIZON - (height >> 1));
        bot = (int16_t)(top + height);
        DrawWallSpan(fb, x, top, bot, hit.side == 1);
        if(top >= 0 && top < RAY_VIEW_H) FB_WHITE(fb, x, top);
        if(bot >= 0 && bot < RAY_VIEW_H) FB_WHITE(fb, x, bot);
    }
}

static void DrawEnemies(const RayGame_t* game, uint8_t* fb, const uint16_t* depth) {
    int16_t cx[RAY_MAX_ENEMIES];
    int16_t w[RAY_MAX_ENEMIES];
    int16_t h[RAY_MAX_ENEMIES];
    int16_t by[RAY_MAX_ENEMIES];
    uint16_t dep[RAY_MAX_ENEMIES];
    uint8_t order[RAY_MAX_ENEMIES];
    uint8_t count = 0;
    for(uint8_t i = 0; i < RAY_MAX_ENEMIES; i++) {
        if(!ray_game_enemy_view(game, i, &cx[i], &w[i], &h[i], &by[i], &dep[i])) continue;
        order[count++] = i;
    }
    for(uint8_t i = 0; i < count; i++) {
        for(uint8_t j = (uint8_t)(i + 1); j < count; j++) {
            if(dep[order[j]] > dep[order[i]]) {
                uint8_t tmp = order[i]; order[i] = order[j]; order[j] = tmp;
            }
        }
    }
    for(uint8_t oi = 0; oi < count; oi++) {
        uint8_t i = order[oi];
        int16_t left = (int16_t)(cx[i] - (w[i] >> 1));
        int16_t top = (int16_t)(by[i] - h[i]);
        int16_t x0 = left < 0 ? 0 : left;
        int16_t x1 = (int16_t)(left + w[i]); if(x1 > RAY_VIEW_W) x1 = RAY_VIEW_W;
        int16_t y0 = top < 0 ? 0 : top;
        int16_t y1 = by[i]; if(y1 > RAY_VIEW_H) y1 = RAY_VIEW_H;
        if(x1 <= x0 || y1 <= y0) continue;
        {
            uint16_t ustep = DivU16(8192u, (uint16_t)(w[i] < 1 ? 1 : w[i]));
            uint16_t vstep = DivU16(8192u, (uint16_t)(h[i] < 1 ? 1 : h[i]));
            for(int16_t x = x0; x < x1; x++) {
                uint8_t u = (uint8_t)(MulU16((uint16_t)(x - left), ustep) >> 8);
                uint16_t vacc = (uint16_t)(MulU16((uint16_t)(y0 - top), vstep) >> 8);
                if(depth[x] <= dep[i]) continue;
                if(u > 31) u = 31;
                for(int16_t y = y0; y < y1; y++) {
                    uint8_t v = (uint8_t)(vacc >> 8);
                    uint8_t px;
                    if(v > 31) v = 31;
                    px = ENEMY_SPRITE[v][u];
                    if(px == 0) {
                        if(ENEMY_HALO[v][u]) FB_WHITE(fb, x, y);
                    } else if(px == 2) {
                        FB_WHITE(fb, x, y);
                    } else {
                        FB_BLACK(fb, x, y);
                    }
                    vacc = (uint16_t)(vacc + vstep);
                }
            }
        }
    }
}

static void DrawGun(const RayGame_t* game, uint8_t* fb) {
    int16_t gx = (int16_t)((RAY_VIEW_W - 64) / 2);
    int16_t gy = 40;
    if(game->muzzle_flash != 0) gy = 42;
    for(uint8_t y = 0; y < 24; y++) {
        for(uint8_t x = 0; x < 64; x++) {
            uint8_t px = GUN_SPRITE[y][x];
            if(px == 0) {
                if(GUN_HALO[y][x]) FB_WHITE(fb, (int16_t)(gx + x), (int16_t)(gy + y));
            } else if(px == 1) {
                FB_BLACK(fb, (int16_t)(gx + x), (int16_t)(gy + y));
            } else {
                FB_WHITE(fb, (int16_t)(gx + x), (int16_t)(gy + y));
            }
        }
    }
}

static void DrawFlash(const RayGame_t* game, uint8_t* fb) {
    int16_t cx = RAY_VIEW_W / 2;
    int16_t cy = 34;
    if(game->muzzle_flash == 0) return;
    for(int16_t dy = -6; dy <= 6; dy++) {
        for(int16_t dx = -6; dx <= 6; dx++) {
            int16_t man = (int16_t)((dx < 0 ? -dx : dx) + (dy < 0 ? -dy : dy));
            if(man > 6) continue;
            if(man >= 5) FB_BLACK(fb, (int16_t)(cx + dx), (int16_t)(cy + dy));
            else FB_WHITE(fb, (int16_t)(cx + dx), (int16_t)(cy + dy));
        }
    }
}

static void DrawCrosshair(uint8_t* fb) {
    static const uint8_t CROSS[5] = {0x04, 0x04, 0x1f, 0x04, 0x04};
    int16_t cx = RAY_VIEW_W / 2;
    int16_t cy = RAY_HORIZON;
    for(uint8_t y = 0; y < 5; y++) {
        for(uint8_t x = 0; x < 5; x++) {
            if(CROSS[y] & (uint8_t)(1u << (4 - x))) {
                FB_INVERT(fb, (int16_t)(cx - 2 + x), (int16_t)(cy - 2 + y));
            }
        }
    }
}

void ray_render_frame(
    const RayGame_t* game,
    uint8_t* fb,
    uint16_t* depth,
    int16_t* ray_x,
    int16_t* ray_y
) {
    PrepareRays(game, ray_x, ray_y);
    DrawFloor(fb);
    DrawWalls(game, fb, depth, ray_x, ray_y);
    DrawEnemies(game, fb, depth);
    DrawGun(game, fb);
    DrawFlash(game, fb);
    DrawCrosshair(fb);
    DrawBitmap(0, 0, RAY_VIEW_W, RAY_VIEW_H, fb);
}
